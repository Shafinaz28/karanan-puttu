export function formatPrice(amount) {
  return new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 0,
  }).format(amount)
}

/** Customer-facing title without repeating fabric on every card and heading. */
export function productDisplayTitle(product, options = {}) {
  const { includeLine = true, short = false } = options
  if (short) return product.name
  if (includeLine && product.line) return `${product.name} — ${product.line}`
  return product.name
}

export function resolveShopCategory(product) {
  if (product.shopCategory) return product.shopCategory
  if (/tissue/i.test(`${product.fabric} ${product.category}`)) return "tissue"
  if (product.party) return "party"
  if (product.saleGroup === "traditional" || /traditional/i.test(product.category || "")) return "traditional"
  return "soft"
}

export function resolveCompareAt(product) {
  if (product.compareAt && product.compareAt > product.price) return product.compareAt
  if (resolveShopCategory(product) === "tissue") return 15999
  return 5599
}
