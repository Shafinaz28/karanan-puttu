create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'Soft Silk',
  price integer not null default 2799,
  badge text,
  sale_group text default 'soft',
  line text,
  featured boolean default false,
  party boolean default false,
  fabric text default 'Soft silk',
  length text default '6.3 metres',
  color text,
  description text,
  image text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.products enable row level security;

drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products"
  on public.products
  for select
  to anon, authenticated
  using (active = true);

drop policy if exists "Authenticated can manage products" on public.products;
create policy "Authenticated can manage products"
  on public.products
  for all
  to authenticated
  using ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

truncate public.products restart identity;

